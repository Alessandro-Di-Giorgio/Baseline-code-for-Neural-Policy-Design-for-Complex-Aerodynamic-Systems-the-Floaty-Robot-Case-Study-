def quantize_residual(r):
    """mapAngleToUint8 on the ESP32 (same bounds as TorchPolicy.h)."""
    x = np.clip(r, U_MIN, U_MAX)
    q = np.floor((x - U_MIN) / (U_MAX - U_MIN) * 255.0 + 0.5)   # = lroundf for x >= 0
    return np.clip(q, 0, 255).astype(np.uint8)


def dequantize_residual(q):
    return U_MIN + q.astype(np.float64) / 255.0 * (U_MAX - U_MIN)


class ElqrResidualController:
    """
    Stateful, batched. Call reset(), then step(e_t, e_prev) every 20 ms.
    Returns the residual actually received by the Crazyflie.

    Internal state:
        xh: last 5 dx = -e   (x_ref is the constant hover reference)
        uh: replica of the last 5 APPLIED total inputs (LQR + residual, clamped)
    """

    def __init__(self, design, gain_scale=1.0, quantize=True):
        self.F = design["F"]
        self.r_offset = design["r_offset"]
        self.Kt = design["lqr"]["K_star_t"]
        self.Ktm1 = design["lqr"]["K_star_tm1"]
        self.Ku = design["lqr"]["K_u_diag"]
        self.gain_scale = float(gain_scale)
        self.quantize = bool(quantize)
        self.xh = None
        self.uh = None

    def reset(self):
        self.xh = None
        self.uh = None

    def step(self, e_t, e_prev):
        e_t = np.asarray(e_t, dtype=np.float64)
        e_prev = np.asarray(e_prev, dtype=np.float64)
        Bn = e_t.shape[0]

        if self.xh is None:
            self.xh = np.repeat(-e_prev[:, None, :], SEQ, axis=1)
            self.xh[:, -1, :] = -e_t
            self.uh = np.zeros((Bn, SEQ, N_U))
        else:
            self.xh = np.concatenate([self.xh[:, 1:], -e_t[:, None]], axis=1)

        z = np.concatenate([self.xh.reshape(Bn, NZ_X), self.uh.reshape(Bn, NZ_U)], axis=1)
        r = self.gain_scale * (self.r_offset[None, :] - z @ self.F.T)

        if self.quantize:
            r = dequantize_residual(quantize_residual(r))
        else:
            r = np.clip(r, U_MIN, U_MAX)

        # Replica of what the Crazyflie applies
        u_base = (
            self.uh[:, -1] * self.Ku[None, :]
            + rotate_xy_error_by_yaw(e_t) @ self.Kt.T
            + rotate_xy_error_by_yaw(e_prev) @ self.Ktm1.T
        )
        u = np.clip(u_base + r, U_MIN, U_MAX)
        self.uh = np.concatenate([self.uh[:, 1:], u[:, None]], axis=1)
        return r


