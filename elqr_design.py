def _fmt(arr):
    return ", ".join(f"{float(v):.9e}f" for v in np.ravel(arr))


def export_header(design, path, gain_scale=1.0, comment=""):
    F = design["F"]
    lqr = design["lqr"]
    lines = []
    lines.append("// Auto-generated by elqr_design.export_header -- do not edit by hand.")
    if comment:
        for c in comment.splitlines():
            lines.append(f"// {c}")
    lines.append("#ifndef ELQR_GAINS_H")
    lines.append("#define ELQR_GAINS_H")
    lines.append("")
    lines.append("namespace elqr {")
    lines.append("")
    lines.append("static constexpr int N_X = 12;")
    lines.append("static constexpr int N_U = 4;")
    lines.append("static constexpr int SEQ = 5;")
    lines.append("static constexpr int NZ  = 80;  // z = [dx_{t-4..t} (60), u_{t-5..t-1} (20)], dx = -e")
    lines.append("")
    lines.append(f"static constexpr float GAIN_SCALE = {gain_scale:.6f}f;")
    lines.append("")
    lines.append("// Residual: r = GAIN_SCALE * (R_OFFSET - F z)")
    lines.append("static const float F[N_U][NZ] = {")
    for i in range(N_U):
        lines.append(f"  {{ {_fmt(F[i])} }},")
    lines.append("};")
    lines.append(f"static const float R_OFFSET[N_U] = {{ {_fmt(design['r_offset'])} }};")
    lines.append("")
    lines.append("// Replica of the Crazyflie LQR (needed for the u history)")
    lines.append("static const float K_STAR_T[N_U][N_X] = {")
    for i in range(N_U):
        lines.append(f"  {{ {_fmt(lqr['K_star_t'][i])} }},")
    lines.append("};")
    lines.append("static const float K_STAR_TM1[N_U][N_X] = {")
    for i in range(N_U):
        lines.append(f"  {{ {_fmt(lqr['K_star_tm1'][i])} }},")
    lines.append("};")
    lines.append(f"static const float K_U[N_U] = {{ {_fmt(lqr['K_u_diag'])} }};")
    lines.append("")
    lines.append("// Saturation of the total input (and of the transmitted residual)")
    lines.append(f"static const float U_MIN[N_U] = {{ {_fmt(U_MIN)} }};")
    lines.append(f"static const float U_MAX[N_U] = {{ {_fmt(U_MAX)} }};")
    lines.append("")
    lines.append("}  // namespace elqr")
    lines.append("")
    lines.append("#endif")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


def save_design_json(design, path, extra=None):
    out = {k: (v.tolist() if isinstance(v, np.ndarray) else v)
           for k, v in design.items() if k not in ("lqr", "P", "Qbar", "S", "Rr")}
    out["lqr"] = {k: v.tolist() for k, v in design["lqr"].items()}
    if extra:
        out.update(extra)
    with open(path, "w") as f:
        json.dump(out, f, indent=2)
    return path


def load_design_json(path):
    """Rebuild the arrays needed by ElqrResidualController from elqr_design.json."""
    with open(path) as f:
        d = json.load(f)
    out = {k: (np.asarray(v, dtype=np.float64) if isinstance(v, list) else v)
           for k, v in d.items() if k != "lqr"}
    out["lqr"] = {k: np.asarray(v, dtype=np.float64) for k, v in d["lqr"].items()}
    return out
