"""
Ensemble-LQR residual ("ELQR") -- numpy/scipy core.

No torch in here, so it can be unit-tested and reused anywhere.

Idea
----
Your NN outputs a residual r_t that is added to the fixed LQR:

    u_t = clamp( K_u*u_{t-1} + K_t*rot(e_t) + K_tm1*rot(e_{t-1}) + r_t )

This module replaces the NN with a *model-based* residual:

  1. The ensemble's history model x_{t+1} = f(x_{t-4..t}, u_{t-5..t-1})
     is identified as an affine model around hover (done in elqr_main.py by
     least squares on closed-loop data generated by each ensemble member).
  2. The history is stacked into an 80-dim state
        z_t = [x_{t-4}, ..., x_t, u_{t-5}, ..., u_{t-1}]   (deviations)
  3. The *existing* LQR is folded into the plant (it is linear in z at
     hover, where the yaw rotation is the identity).
  4. A DARE (with cross term, because the cost penalises the TOTAL u
     = K_c z + r, exactly as your training loss with u_penalty_mode
     "total_u") gives the optimal residual
        r_t = r_ff - F (z_t - z_eq)
     r_ff is an optional feed-forward that cancels the model's hover drift.

On the ESP32 this is a 4x80 matrix-vector product plus a replica of the
LQR (needed to know the u history). It uses the same interface as the NN:
e_t in (12 float16), 4 uint8 out.
"""

import json
import numpy as np
from scipy.linalg import solve_discrete_are

N_X = 12
N_U = 4
SEQ = 5
NZ_X = SEQ * N_X        # 60
NZ_U = SEQ * N_U        # 20
NZ = NZ_X + NZ_U        # 80

# Total-u saturation used everywhere in your code (and on the CF side)
OUT_MIN_02, OUT_MAX_02 = -0.692699, 0.407301
OUT_MIN_13, OUT_MAX_13 = -0.407301, 0.692699
U_MIN = np.array([OUT_MIN_02, OUT_MIN_13, OUT_MIN_02, OUT_MIN_13], dtype=np.float64)
U_MAX = np.array([OUT_MAX_02, OUT_MAX_13, OUT_MAX_02, OUT_MAX_13], dtype=np.float64)


def xblk(k):
    """Slice of x_{t-4+k} inside z (k=4 is newest, x_t)."""
    return slice(k * N_X, (k + 1) * N_X)


def ublk(k):
    """Slice of u_{t-5+k} inside z (k=4 is newest, u_{t-1})."""
    return slice(NZ_X + k * N_U, NZ_X + (k + 1) * N_U)


